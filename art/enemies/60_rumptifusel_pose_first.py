PARTS = (BODY, EDGES, SOFTEN, HEAD, RIB, EYES, PORES, TUFTS)

def pose():
    """{pixel: letter}: the parts set down back to front."""
    g = {}
    for part in PARTS:
        for y, x0, t in part:
            for x, c in enumerate(t, x0):
                if c != '.': g[(x, y)] = c
    assert all(0 <= x < W and 1 <= y < H for x, y in g), sorted(p for p in g if not (0 <= p[0] < W and 1 <= p[1] < H))
    body = {(x, y) for y, x0, t in BODY for x, c in enumerate(t, x0) if c != '.'}
    for y, x, t in TUFTS: assert (x, y) not in body and any(flat_parts.add((x, y), d) in body for d in flat_parts.N4), (y, x)   # a tuft stands off the outline, touching it
    return g

FRAMES = lambda: [pose()]

def numbers(g):
    """What the bible measures, of one frame."""
    edge = {p for p in g if any(flat_parts.add(p, d) not in g for d in flat_parts.N4)}
    inner = sum(1 for p, c in g.items() if c == 'K' and p not in edge)
    bare = sorted(p for p in edge if g[p] != 'K')
    xs = [p[0] for p in g]; ys = [p[1] for p in g]
    return {'box': (min(xs), min(ys), max(xs), max(ys)), 'size': (max(xs) - min(xs) + 1, max(ys) - min(ys) + 1), 'colours': len(set(g.values()) - {'K'}),
            'black inside %': round(100 * inner / len(g), 1), 'edge that is black %': round(100 * (len(edge) - len(bare)) / len(edge), 1), 'open edge': bare[:8],
            'at the frame middle': g.get((W // 2, H // 2), 'nothing'), 'frame middle': (W / 2, H / 2)}

