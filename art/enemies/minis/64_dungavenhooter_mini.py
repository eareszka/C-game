def grid(s):
    """A drawn grid, centred, its bottom row on the ground, one black outline round it, its eyes and nostrils
    black inside."""
    rows = s.strip('\n').split('\n')
    h, w = len(rows), max(map(len, rows))
    g = {(x + (minis.W - w) // 2, y + minis.H - 1 - h): c for y, r in enumerate(rows) for x, c in enumerate(r) if c != '.'}
    out = ff.outline({p: ('M' if c == 'K' else c) for p, c in g.items()})
    out.update({p: 'K' for p, c in g.items() if c == 'K'})
    return out


