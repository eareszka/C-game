def line(pts, c):
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        n = max(abs(x1 - x0), abs(y1 - y0), 1)
        for i in range(n + 1):
            dot(im, round(x0 + (x1 - x0) * i / n), round(y0 + (y1 - y0) * i / n), c)


