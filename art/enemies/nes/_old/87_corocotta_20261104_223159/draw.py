W, H = 60, 68
base = canvas(W, H)
im = None


def begin():
    global im
    im = canvas(W, H)


def end():
    """Lay the part down, with a black line on whatever it overlaps."""
    a, b = im.load(), base.load()
    for y in range(H):
        for x in range(W):
            if a[x, y][3] or not b[x, y][3]:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                if 0 <= x + dx < W and 0 <= y + dy < H and a[x + dx, y + dy][3]:
                    b[x, y] = BLACK
                    break
    base.alpha_composite(im)


def ln(pts, c):
    ImageDraw.Draw(im).line(pts, fill=rgba(c), width=1)


def px(pts, c):
    for x, y in pts:
        rect(im, x, y, 1, 1, c)


