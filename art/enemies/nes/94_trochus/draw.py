from pix import *
from math import cos, sin, pi

im = canvas(76, 76)
K = '000000'
G = 'c9a433'
L = 'f4ce80'
S = '94703d'
B = '375a94'
D = '37387b'
H = '84a7e9'

# The crown is made of twelve broad, faceted shell spines.
spines = [
    ([(31,19),(33,9),(37,0),(40,6),(41,17)], [(34,15),(35,8),(37,2),(38,13)]),
    ([(44,18),(49,7),(53,5),(53,12),(51,24)], [(47,18),(50,10),(52,8),(51,18)]),
    ([(55,23),(64,15),(70,14),(67,21),(60,31)], [(58,24),(65,18),(68,17),(63,24)]),
    ([(61,31),(69,30),(75,34),(70,37),(62,40)], [(64,32),(69,32),(72,34),(64,35)]),
    ([(61,43),(68,45),(75,51),(67,52),(57,50)], [(63,45),(68,47),(71,50),(62,48)]),
    ([(54,54),(60,59),(63,68),(56,65),(49,59)], [(56,57),(59,61),(60,65),(54,61)]),
    ([(42,60),(46,67),(45,75),(40,71),(36,61)], [(40,63),(43,68),(44,72),(40,69)]),
    ([(29,58),(30,67),(26,74),(23,69),(23,57)], [(26,60),(27,66),(25,71),(25,64)]),
    ([(18,51),(17,61),(11,66),(10,59),(12,47)], [(14,52),(14,59),(12,62),(12,55)]),
    ([(14,37),(10,45),(0,47),(4,41),(11,34)], [(11,39),(7,43),(3,45),(6,41)]),
    ([(16,25),(7,26),(2,20),(9,20),(21,20)], [(16,23),(9,23),(5,21),(14,21)]),
    ([(23,20),(16,14),(15,5),(21,8),(29,17)], [(24,18),(19,13),(17,8),(21,11)]),
]
for edge, light in spines:
    poly(im, edge, S)
    # The upper-left face is the broad gold facet.
    c = [(round((x * 4 + 38) / 5), round((y * 4 + 38) / 5)) for x,y in edge]
    poly(im, c, G)
    poly(im, light, L)

# The shell's angular rim overlaps and binds all the spine roots.
rim = [(28,12),(45,12),(45,14),(52,16),(59,23),(62,30),
       (64,30),(64,45),(62,45),(60,52),(53,59),(46,62),
       (30,62),(30,60),(23,58),(16,51),(13,44),(12,31),
       (15,24),(21,17),(28,14)]
poly(im, rim, B)
poly(im, [(28,14),(45,14),(52,18),(58,24),(61,31),(62,44),
          (58,51),(52,57),(45,60),(31,60),(24,56),(18,50),
          (15,43),(14,32),(17,25),(23,19)], B)

# Facets on the rim follow the light, with hard, broken highlight runs.
poly(im, [(16,33),(18,26),(24,20),(29,17),(43,16),(43,18),
          (29,19),(25,22),(20,27),(19,34)], H)
poly(im, [(58,28),(61,32),(62,44),(58,51),(52,57),(45,60),
          (31,60),(25,57),(32,57),(44,57),(50,54),(56,48),
          (59,42)], D)

# Eight cut chambers and thick spokes make this a wheel, not a disc.
cx, cy = 38, 37
def turn(points, angle):
    a = angle * pi / 180
    return [(round(cx + x*cos(a)-y*sin(a)),
             round(cy + x*sin(a)+y*cos(a))) for x,y in points]

for angle in range(0, 360, 45):
    poly(im, turn([(6,-3),(16,-10),(19,-6),(20,0),(8,1)], angle), K)
    poly(im, turn([(8,-3),(16,-8),(18,-6),(19,-1),(9,0)], angle), D)
    poly(im, turn([(15,-5),(17,-4),(17,-3),(15,-4)], angle), B)

# Visible ribs have a lit edge, and a short cross-joint at the rim.
for angle in (0,45,90,135,180,225,270,315):
    poly(im, turn([(8,2),(18,2),(20,4),(17,4),(8,3)], angle), B)
    poly(im, turn([(22,1),(23,1),(23,2),(22,2)], angle), K)
for angle in (180,225,270):
    poly(im, turn([(8,2),(18,2),(18,3),(8,3)], angle), H)

# Separate bevels articulate the eight rim plates and spoke shoulders.
for angle in range(0, 360, 45):
    tone = H if angle in (180,225,270) else D
    poly(im, turn([(21,-7),(23,-5),(24,-2),(23,-2),(22,-5),(20,-7)], angle), tone)
    poly(im, turn([(11,4),(14,4),(14,5),(12,5)], angle), tone)
    poly(im, turn([(23,-8),(24,-7),(24,-5)], angle), K)

# The solid boss is an animal's armored central hub, without a face.
poly(im, [(34,31),(41,31),(45,35),(45,40),(41,44),(35,44),(31,40),(31,35)], K)
poly(im, [(35,32),(40,32),(43,35),(43,40),(40,42),(35,42),(33,39),(33,35)], B)
poly(im, [(35,32),(40,32),(41,34),(36,34),(34,37),(33,36)], H)
poly(im, [(42,37),(43,37),(43,40),(40,42),(35,42),(35,40),(40,40)], D)

im = outline(im)
save(im)
