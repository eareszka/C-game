# Chipekwe, head-on. Parts, back to front, and where each attaches:
# hind foot L/R  - bottom of each shank, two claws each
# hind shank L/R - below each thigh, down to the hind foot
# thigh L/R      - comes out from under the belly
# belly          - under the chest, behind the snout, above the thighs
# hump           - behind the head, top centre
# foot L/R       - bottom of each foreleg
# foreleg L/R    - below the shoulder, down to the foot
# shin L/R       - lower foreleg, below a slanted knee fold, above the foot
# shoulder L/R   - beside the neck, overlapping the top of the foreleg
# shoulder cap L/R - skin fold on top of each shoulder, under the ear
# neck fold L/R  - between shoulder and head
# ear L/R        - on the shoulder, behind the head's top corners
# toes L/R x3    - front of each foot, each with its own claw
# forehead       - top of the head, its lower edge is the brow line
# face L/R       - below the brow line, carries the eye
# cheek L/R      - below the face, above the snout
# chin           - under the snout
# snout          - bottom of the head
# tusk L/R       - each side of the snout
# horn           - rises from the snout between the eyes

