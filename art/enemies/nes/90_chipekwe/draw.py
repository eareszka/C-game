def part(pts, base, shade_pts=None, shade=None):
    # one closed part: flat base, shadow clipped inside it, black line all round
    mask = Image.new('L', im.size, 0)
    ImageDraw.Draw(mask).polygon(pts, fill=255)
    layer = Image.new('RGBA', im.size, rgba(base))
    if shade_pts:
        ImageDraw.Draw(layer).polygon(shade_pts, fill=rgba(shade))
    im.paste(layer, (0, 0), mask)
    ImageDraw.Draw(im).polygon(pts, outline=BLACK)


