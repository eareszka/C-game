"""Packs the cliff rock texture into src/cliff_texture.inc.

    python art/cliffs/gen_cliff_texture.py

art/cliffs/cliff_texture.aseprite (exported beside it as cliff_texture.png) is
drawn through the pixel plugin from cliff_texture_design.py: a tileable square
of rock in four grey values -- crack, shade, base, lit. It is packed the
bible's way (art/direction/OVERWORLD_STYLE.md, Rock: a base, a shade, black
cracks; no lit tone, no dither): every stone one flat tone (flat()). The game
paints every cliff wall from it in world coordinates (src/cliff_paint.inc),
swapping the values for the island's ore ramp, and the oasis's rock from the
same rows (oasis_bake in src/dungeon.cpp), so only the values are stored here.
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
ART = os.path.join(HERE, "cliff_texture.png")
OUT = os.path.join(ROOT, "src", "cliff_texture.inc")
VALUES = {(0, 0, 0): 0, (0x5c, 0x5c, 0x68): 1, (0x8c, 0x8c, 0x98): 2, (0xc4, 0xc4, 0xcc): 3}   # crack, shade, base, lit


def drawn():
    """The drawing's rows, a digit a pixel: '0' crack, '1' shade, '2' base, '3' lit."""
    im = Image.open(ART).convert("RGB")
    n = im.width
    if im.height != n:
        sys.exit("cliff_texture.png must be square, is %dx%d" % (im.width, im.height))
    px = im.load()
    for y in range(n):
        for x in range(n):
            if px[x, y] not in VALUES:
                sys.exit("cliff_texture.png has %s at %d,%d, not one of the four values" % (px[x, y], x, y))
    return ["".join(str(VALUES[px[x, y]]) for x in range(n)) for y in range(n)]


def flat(rows):
    """Rows with every stone -- a piece between cracks, the texture wrapping --
    one tone: its shade if over three in ten of it was dithered dark, else its
    base. (The user, 2026-10-13: "have cliff islands use the same rock
    textures used in oasis caves"; the oasis's rock was this already.)"""
    n = len(rows)
    g, seen = [list(r) for r in rows], set()
    for y0 in range(n):
        for x0 in range(n):
            if g[y0][x0] == '0' or (x0, y0) in seen:
                continue
            part, stack = [], [(x0, y0)]
            seen.add((x0, y0))
            while stack:
                x, y = stack.pop()
                part.append((x, y))
                for q in (((x + 1) % n, y), ((x - 1) % n, y), (x, (y + 1) % n), (x, (y - 1) % n)):
                    if g[q[1]][q[0]] != '0' and q not in seen:
                        seen.add(q)
                        stack.append(q)
            tone = '1' if sum(rows[y][x] == '1' for x, y in part) > 0.3 * len(part) else '2'
            for x, y in part:
                g[y][x] = tone
    return ["".join(r) for r in g]


def main():
    rows = flat(drawn())
    n = len(rows)
    text = "\n".join([
        "// Generated by art/cliffs/gen_cliff_texture.py -- do not edit.",
        "// The rock texture, each stone one flat tone: one digit per pixel, 0 crack, 1 shade, 2 base.",
        "enum { CLIFF_TEX_N = %d };" % n,
        "static const char CLIFF_TEX[CLIFF_TEX_N][CLIFF_TEX_N + 1] = {",
    ] + ["    \"" + r + "\"," for r in rows] + ["};", ""])
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote", os.path.relpath(OUT, ROOT), "(%dx%d)" % (n, n))


if __name__ == "__main__":
    main()
