"""Bake the game's font (art/fonts/Pixuf.ttf, the user's) into bitmaps.

    python tools/gen_font.py

Writes src/font.inc: printable ASCII at the font's own size (8px, where it
draws with no grey), each glyph as 8 rows of bits (bit 7 = its left pixel)
and the pixels the pen moves on after it -- the font is proportional. After
it, the game's own glyphs (OWN), drawn to Pixuf's grid: capitals on rows 1-6,
a pixel's gap in the advance.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FIRST, LAST, SIZE = 32, 126, 8

# The game's own glyphs, after '~' (core.h names them): rows of the 8-row
# cell, '#' a pixel, and the advance.
OWN = [
    ('cursor', 4, ['', '#', '##', '###', '###', '##', '#', '']),     # 0x7F, a solid right triangle the capitals' height
    ('more',   6, ['', '', '', '#####', ' ###', '  #', '', '']),     # 0x80, the speech box's "more" arrow
]

font = ImageFont.truetype(str(ROOT / 'art/fonts/Pixuf.ttf'), SIZE)
rows, adv = [], []
for c in range(FIRST, LAST + 1):
    im = Image.new('L', (16, SIZE), 0)
    ImageDraw.Draw(im).text((0, 0), chr(c), font=font, fill=255)
    px = im.load()
    assert all(px[x, y] in (0, 255) for x in range(16) for y in range(SIZE)), f'grey in {chr(c)!r}'
    assert not any(px[x, y] for x in range(8, 16) for y in range(SIZE)), f'{chr(c)!r} wider than 8'
    rows.append([sum(0x80 >> x for x in range(8) if px[x, y]) for y in range(SIZE)])
    adv.append(int(font.getlength(chr(c))))

names = [{'\\': 'backslash'}.get(chr(c), chr(c)) for c in range(FIRST, LAST + 1)]   # a \ ending a // comment would join the next line to it
for name, a, glyph in OWN:
    rows.append([sum(0x80 >> x for x, ch in enumerate(line) if ch == '#') for line in glyph])
    adv.append(a)
    names.append(name)
LAST += len(OWN)

out = ['// Generated by tools/gen_font.py -- do not edit.',
       '// The game\'s font (art/fonts/Pixuf.ttf): printable ASCII, 8 rows of bits a',
       '// glyph (bit 7 its left pixel), and how far the pen moves after each;',
       '// past ~, the game\'s own glyphs (the menus\' cursor, the "more" arrow).',
       f'enum {{ FONT_FIRST = {FIRST}, FONT_LAST = {LAST} }};',
       'static const Uint8 FONT_ROWS[][8] = {']
for name, r in zip(names, rows):
    out.append('    {' + ','.join(f'0x{b:02X}' for b in r) + f'}},  // {name}')
out += ['};', 'static const Uint8 FONT_ADV[] = {']
for i in range(0, len(adv), 16):
    out.append('    ' + ','.join(str(a) for a in adv[i:i + 16]) + ',')
out.append('};')
(ROOT / 'src/font.inc').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
print('src/font.inc:', len(rows), 'glyphs, advances', min(adv), '-', max(adv))
